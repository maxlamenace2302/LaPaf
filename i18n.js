/* ------------------------------------------------------------
   Apply translations
   - data-i18n="key"            → element.innerHTML = t(key)
   - data-i18n-attr="alt:key|title:key"  → element[attr] = t(key)
   - data-i18n-title="key"      → document.title (root only)
   ------------------------------------------------------------ */

(function() {
  const DEFAULT_LANG = "fr";
  const SUPPORTED = ["fr", "en", "de", "it"];

  function getLang() {
    const saved = localStorage.getItem("auberge_lang");
    if (saved && SUPPORTED.includes(saved)) return saved;
    const browser = (navigator.language || "fr").slice(0, 2).toLowerCase();
    return SUPPORTED.includes(browser) ? browser : DEFAULT_LANG;
  }

  function t(lang, key) {
    return (window.I18N[lang] && window.I18N[lang][key]) || window.I18N[DEFAULT_LANG][key] || key;
  }

  function applyTranslations(lang) {
    // Plain content
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      el.innerHTML = t(lang, key);
    });

    // Attribute translations
    document.querySelectorAll("[data-i18n-attr]").forEach(el => {
      const spec = el.getAttribute("data-i18n-attr");
      spec.split("|").forEach(pair => {
        const [attr, key] = pair.split(":");
        if (attr && key) el.setAttribute(attr, t(lang, key));
      });
    });

    // <title>
    const titleEl = document.querySelector('[data-i18n-title]');
    if (titleEl) {
      document.title = t(lang, titleEl.getAttribute("data-i18n-title"));
    } else {
      const titleKey = document.documentElement.getAttribute("data-i18n-title");
      if (titleKey) document.title = t(lang, titleKey);
    }

    // <html lang="..">
    document.documentElement.lang = window.I18N[lang]?.htmlLang || lang;

    // Mark active button
    document.querySelectorAll("[data-lang]").forEach(b => {
      b.classList.toggle("is-active", b.getAttribute("data-lang") === lang);
    });

    localStorage.setItem("auberge_lang", lang);
  }

  function init() {
    const initial = getLang();
    applyTranslations(initial);
    document.querySelectorAll("[data-lang]").forEach(b => {
      b.addEventListener("click", () => applyTranslations(b.getAttribute("data-lang")));
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }

  // Expose for debugging
  window.setLang = applyTranslations;
})();
